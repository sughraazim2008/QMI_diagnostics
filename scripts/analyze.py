"""Full statistical analysis of a sweep (Methods 2.9).  Produces tables, figures and a
Markdown report; every number in the report is computed here from the Parquet tables.

Usage
-----
python scripts/analyze.py --main results/main/main.parquet --esn results/main/esn_baseline.parquet \
    [--transfer results/transfer/transfer.parquet --transfer-esn results/transfer/esn_baseline.parquet] \
    [--out results/main/analysis] [--n-boot 2000] [--label "Main sweep"]
"""
import argparse
import json
import os
from pathlib import Path

for v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "VECLIB_MAXIMUM_THREADS"):
    os.environ.setdefault(v, "1")       # the bootstrap is many tiny fits; threads only add overhead

import numpy as np
import pandas as pd

from qrc_qmi import figures as fg
from qrc_qmi import stats as st

M1 = (st.NEG, st.COH, st.TMI) + tuple(st.CONTROLS)


def md(df: pd.DataFrame, digits=3) -> str:
    d = df.copy()
    for c in d.columns:
        if d[c].dtype.kind == "f":
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else f"{v:.{digits}f}")
    head = "| " + " | ".join(map(str, d.columns)) + " |\n|" + "---|" * len(d.columns) + "\n"
    return head + "\n".join("| " + " | ".join(map(str, r)) + " |" for r in d.to_numpy()) + "\n"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--main", required=True)
    p.add_argument("--esn", required=True)
    p.add_argument("--transfer", default=None)
    p.add_argument("--transfer-esn", default=None)
    p.add_argument("--gap-ref", default="results/pilot/gap_ratio.csv")
    p.add_argument("--out", default=None)
    p.add_argument("--task", default="narma10")
    p.add_argument("--shots", default="s6")
    p.add_argument("--n-boot", type=int, default=2000)
    p.add_argument("--n-boot-gbt", type=int, default=200)
    p.add_argument("--margin", type=float, default=0.02)
    p.add_argument("--label", default="")
    p.add_argument("--keep-esp-failures", action="store_true",
                   help="sensitivity analysis: keep configurations that fail the echo-state check")
    a = p.parse_args()

    raw = pd.read_parquet(a.main)
    esn = pd.read_parquet(a.esn)
    gap_ref = pd.read_csv(a.gap_ref) if Path(a.gap_ref).exists() else None
    out = Path(a.out or Path(a.main).parent / "analysis")
    (out / "figures").mkdir(parents=True, exist_ok=True)
    P = dict(gap_ref=gap_ref, drop_esp_failures=not a.keep_esp_failures)
    df = st.prepare(raw, esn, a.task, a.shots, **P)
    R, S = [], {}           # report lines, JSON summary
    kw = dict(margin=a.margin, n_boot=a.n_boot)

    # ---------------------------------------------------------------- 0. data overview
    R += [f"# Analysis report{': ' + a.label if a.label else ''}\n",
          f"Source: `{a.main}` ({len(raw)} configurations), baseline `{a.esn}`. "
          f"Primary outcome: {a.task}, shots tag `{a.shots}`. Bootstrap resamples: {a.n_boot}.\n",
          "All numbers below are generated by `scripts/analyze.py`.\n", "## 0. Data overview\n"]
    esp = raw.assign(fail=~raw["esp_ok"]).groupby(["N", "channel", "gamma"])["fail"].mean().unstack("gamma")
    S["n_raw"], S["n_used"] = len(raw), len(df)
    S["esp_fail_fraction"] = float((~raw["esp_ok"]).mean())
    R += [f"Echo-state check (trace distance < 1e-6 after washout) failed for "
          f"**{(~raw['esp_ok']).sum()} of {len(raw)}** configurations; these are "
          f"{'KEPT in this sensitivity analysis' if a.keep_esp_failures else 'excluded'}, leaving "
          f"{len(df)} configurations in {df['cell'].nunique()} grid cells. Quantiles of the distance "
          f"(10%, 50%, 90%, max): " + ", ".join(f"{q:.1e}" for q in raw["esp_dist"].quantile([0.1, 0.5, 0.9, 1.0])) + ".\n",
          "Fraction failing, by N, channel (rows) and γ (columns):\n", md(esp.reset_index(), 2)]
    lam_cols = [c for c in raw.columns if c.startswith("lam_upper_") and c.endswith(a.shots)]
    R += ["Share of ridge fits selecting the largest allowed penalty (λ = 1): "
          + ", ".join(f"{c[10:]}: {raw[c].mean():.1%}" for c in lam_cols) + "\n",
          "Classical baselines (test NRMSE):\n",
          md(esn[["task", "D", "esn_nrmse", "esn_nrmse_sd_seeds", "esn_untuned_nrmse", "linquad_nrmse",
                  "esn_leak", "esn_radius", "esn_in_scale", "esn_bias_scale"]], 4)]

    # ---------------------------------------------------------------- 1. descriptives
    R.append("## 1. Performance gap\n")
    by = ["N", "channel"] + (["regime"] if "regime" in df else [])
    desc = df.groupby(by).agg(n=("delta", "size"), nrmse_qrc=("nrmse_qrc", "median"),
                              nrmse_qrc_best=("nrmse_qrc", "min"), nrmse_esn=("nrmse_esn", "first"),
                              delta_median=("delta", "median"), delta_max=("delta", "max"),
                              frac_positive=("delta", lambda v: float((v > 0).mean()))).reset_index()
    desc.to_csv(out / "table_gap_descriptives.csv", index=False)
    S["frac_delta_positive"] = float((df["delta"] > 0).mean())
    S["delta_max"] = float(df["delta"].max())
    R += [f"Δ > 0 (quantum reservoir better than the tuned ESN) in **{(df['delta'] > 0).sum()} of {len(df)}** "
          f"configurations; the largest Δ is {df['delta'].max():.3f}.\n", md(desc)]
    if "linquad_nrmse" in esn:
        lq = esn[esn["task"] == a.task].set_index("D")["linquad_nrmse"]
        beat = (df["nrmse_qrc"] < df["D"].map(lq)).mean()
        S["frac_beating_linquad"] = float(beat)
        R.append(f"Share of quantum configurations beating the linear–quadratic reference: {beat:.1%}.\n")
    fg.scatter_by_channel(df, [st.NEG, st.COH, st.TMI], "delta", out / "figures/delta_vs_diagnostics.png",
                          "Performance gap against the three diagnostics", zero_line=True)
    fg.lines_vs_gamma(df, ["nrmse_qrc", st.NEG, st.COH, st.TMI], out / "figures/vs_gamma.png",
                      "NRMSE and diagnostics against decoherence rate")
    if "ipc_total" in df:
        fg.scatter_by_channel(df, [st.COH, st.NEG, st.TMI], "ipc_total", out / "figures/ipc_vs_diagnostics.png",
                              "Total IPC against the three diagnostics")

    # ---------------------------------------------------------------- 2. collinearity
    R.append("## 2. Relations among diagnostics\n")
    cols = st.available(df, [st.NEG, st.COH, st.TMI, st.PAIR, "diag_classical_corr", "diag_purity",
                             "diag_entropy_per_qubit", "delta"] + (["ipc_total"] if "ipc_total" in df else []))
    df[cols].corr(method="spearman").to_csv(out / "table_spearman.csv")
    fg.correlation_heatmap(df, cols, out / "figures/correlations.png", "Spearman correlations (all configurations)")
    v = st.vif(df, list(M1)).round(2)
    v.to_csv(out / "table_vif.csv")
    sp = df[cols].corr(method="spearman")
    S["spearman_tmi_coherence"] = float(sp.loc[st.TMI, st.COH])
    S["spearman_tmi_negativity"] = float(sp.loc[st.TMI, st.NEG])
    R += [f"Spearman ρ(T/N, coherence) = {sp.loc[st.TMI, st.COH]:.3f}; ρ(T/N, negativity) = "
          f"{sp.loc[st.TMI, st.NEG]:.3f}; ρ(coherence, negativity) = {sp.loc[st.COH, st.NEG]:.3f}.\n",
          "Variance inflation factors in M1:\n", md(v.reset_index().rename(columns={"index": "predictor"}), 2)]
    com = st.commonality(df)
    com.to_csv(out / "table_commonality.csv", index=False)
    R += ["Commonality analysis (in-sample R² of Δ beyond the controls):\n", md(com, 4)]

    # ---------------------------------------------------------------- 3. H1a
    R.append("## 3. H1a — does QMI add predictive information?\n")
    subsets = {"pooled": df}
    for ch in sorted(df["channel"].unique()):
        if df.loc[df["channel"] == ch, "cell"].nunique() >= 30:
            subsets[ch] = df[df["channel"] == ch]
    if "regime" in df:
        for g in ("ergodic", "localised"):
            if df.loc[df["regime"] == g, "cell"].nunique() >= 30:
                subsets[g] = df[df["regime"] == g]
    for N in sorted(df["N"].unique()):
        if df["N"].nunique() > 1 and df.loc[df["N"] == N, "cell"].nunique() >= 30:
            subsets[f"N={N}"] = df[df["N"] == N]
    rows = []
    for name, d in subsets.items():
        rows.append(dict(label=f"{name}: + T", **st.nested_gain(d, **kw)))
    primary = rows[0]
    # sensitivity analyses on the pooled data
    sens = [("pooled: + pairwise QMI instead of T", dict(add=[st.PAIR])),
            ("pooled: + T, log-negativity in base", dict(base=[st.LOGNEG, st.COH])),
            ("pooled: + T, relative gap Δ/NRMSE_ESN", dict(y="rel_delta")),
            ("pooled: + T, gradient-boosted trees", dict(model="gbt", n_boot=a.n_boot_gbt, n_repeats=3, boot_repeats=1)),
            ("pooled: + coherence to (negativity, T)", dict(add=[st.COH], base=[st.NEG, st.TMI])),
            ("pooled: + negativity to (coherence, T)", dict(add=[st.NEG], base=[st.COH, st.TMI]))]
    for label, extra in sens:
        rows.append(dict(label=label, **st.nested_gain(df, **{**kw, **extra})))
    for tag in ("s5", "s4"):
        if f"nrmse_{a.task}_{tag}" in raw:
            d = st.prepare(raw, esn, a.task, tag, **P)
            rows.append(dict(label=f"pooled: + T, shots 1e{tag[1]}", **st.nested_gain(d, **kw)))
    h1a = pd.DataFrame(rows)
    h1a.to_csv(out / "table_h1a.csv", index=False)
    S["h1a"] = primary
    fg.forest(h1a, out / "figures/h1a_forest.png", "H1a: added value of QMI", margin=a.margin)
    R += [f"**Primary test (pooled, OLS):** R²_cv(M0) = {primary['r2_m0']:.3f}, R²_cv(M1) = {primary['r2_m1']:.3f}, "
          f"gain = {primary['gain']:+.4f} (95% interval {primary['ci95_lo']:+.4f} to {primary['ci95_hi']:+.4f}; "
          f"90% interval {primary['ci90_lo']:+.4f} to {primary['ci90_hi']:+.4f}). "
          f"Pre-specified decision: **{primary['decision']}**.\n",
          md(h1a[["label", "n", "n_cells", "r2_m0", "r2_m1", "gain", "ci95_lo", "ci95_hi", "ci90_lo",
                  "ci90_hi", "decision"]], 4)]

    # ---------------------------------------------------------------- 4. H1b
    if df["channel"].nunique() == 2:
        R.append("## 4. H1b — does the QMI–Δ relation depend on the channel?\n")
        h1b = st.h1b(df)
        h1b.to_csv(out / "table_h1b.csv", index=False)
        S["h1b"] = h1b.to_dict(orient="records")
        R += ["Standardised model with cluster-robust errors; the interaction is the amplitude-damping "
              "slope minus the dephasing slope.\n",
              md(h1b[["qmi", "slope_dephasing", "se_dephasing", "slope_amplitude_damping",
                      "se_amplitude_damping", "interaction", "se", "p_interaction_holm", "p_tost_holm",
                      "decision"]], 4)]
        sec = [st.channel_interaction(df, q, base=[b for b in (st.NEG, st.COH, st.TMI) if b != q])
               for q in (st.COH, st.NEG)]
        sec = pd.DataFrame(sec)
        sec.to_csv(out / "table_h1b_secondary.csv", index=False)
        R += ["Secondary: channel interactions of coherence and negativity (uncorrected p):\n",
              md(sec[["qmi", "slope_dephasing", "slope_amplitude_damping", "interaction", "se", "p_interaction"]], 4)]

    # ---------------------------------------------------------------- 5. H1c
    R.append("## 5. H1c — transfer\n")
    tr, pairs = [], {}
    tkw = dict(n_boot=a.n_boot)

    def add(label, src, tgt):
        if len(src) < 40 or len(tgt) < 40:
            return
        tr.append(st.transfer(src, tgt, M1, label=label, **tkw))
        use = [c for c in st.available(src, list(M1)) if c in tgt.columns]
        pairs[label] = (st._fit_predict(src[use].to_numpy(float), src["delta"].to_numpy(float),
                                        tgt[use].to_numpy(float)), tgt["delta"].to_numpy(float))

    if df["channel"].nunique() == 2:
        dep, ad = df[df["channel"] == "dephasing"], df[df["channel"] == "amplitude_damping"]
        add("channel: dephasing → amplitude damping", dep, ad)
        add("channel: amplitude damping → dephasing", ad, dep)
    task_src, task_esn = (raw, esn)
    if a.transfer:
        traw, tesn = pd.read_parquet(a.transfer), pd.read_parquet(a.transfer_esn or a.esn)
        tdf = st.prepare(traw, tesn, a.task, a.shots, **P)
        add(f"size: N={sorted(df['N'].unique())} → N={sorted(tdf['N'].unique())}", df, tdf)
        task_src, task_esn = traw, tesn
    src = st.prepare(task_src, task_esn, a.task, a.shots, **P)
    for t2 in ("narma5", "narma20", "mackey_glass"):
        if f"nrmse_{t2}_{a.shots}" in task_src and (task_esn["task"] == t2).any():
            prefix = "diagmg_" if t2 == "mackey_glass" else "diag_"
            add(f"task: {a.task} → {t2}", src, st.prepare(task_src, task_esn, t2, a.shots, diag_prefix=prefix, **P))
    if tr:
        h1c = pd.DataFrame(tr)
        h1c.to_csv(out / "table_h1c.csv", index=False)
        S["h1c"] = h1c.to_dict(orient="records")
        fg.predicted_vs_observed(pairs, out / "figures/h1c_transfer.png", "Transfer of the source model M1")
        R += ["Transfer ratio = R²(target) / R²_cv(source); H0c is rejected only if the lower 95% bound is "
              "≥ 0.70 in every transfer.\n",
              md(h1c[["transfer", "n_source", "n_target", "r2_cv_source", "r2_target", "ratio", "ratio_lo",
                      "ratio_hi", "spearman", "spearman_lo", "spearman_hi", "passes"]])]
        S["h1c_all_pass"] = bool(h1c["passes"].all())

    if gap_ref is not None:
        fg.gap_ratio_map(gap_ref, out / "figures/gap_ratio_map.png")
    (out / "report.md").write_text("\n".join(R))
    (out / "summary.json").write_text(json.dumps(S, indent=2, default=float))
    print("\n".join(R))


if __name__ == "__main__":
    main()
